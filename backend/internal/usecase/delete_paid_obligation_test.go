// TestRKASRealizationDecrementation tests the mathematical invariant of realisasi reduction
func TestRKASRealizationDecrementation(t *testing.T) {
	initialRealized := 1500000.0
	paymentToDelete := 350000.0

	// Simulating GREATEST(0, realized_amount - amount)
	updatedRealized := initialRealized - paymentToDelete
	if updatedRealized < 0 {
		updatedRealized = 0
	}

	expected := 1150000.0
	if updatedRealized != expected {
		t.Fatalf("Expected realized amount to be %f, got %f", expected, updatedRealized)
	}

	// Test boundary case: deleting payment greater than recorded realization (should not become negative)
	oversizedPayment := 2000000.0
	clampedRealized := initialRealized - oversizedPayment
	if clampedRealized < 0 {
		clampedRealized = 0
	}

	if clampedRealized != 0 {
		t.Fatalf("Expected clamped realization to be 0, got %f", clampedRealized)
	}
}

// TestPaymentTypeDeleteSafetyPolicy tests the safety check when deleting a payment type with paid obligations
func TestPaymentTypeDeleteSafetyPolicy(t *testing.T) {
	type obligationItem struct {
		id         uuid.UUID
		paidAmount float64
	}

	tests := []struct {
		name         string
		settingValue string
		obligations  []obligationItem
		expectError  bool
	}{
		{
			name:         "Payment type with paid obligations cannot be deleted in safe mode",
			settingValue: "false",
			obligations: []obligationItem{
				{id: uuid.New(), paidAmount: 0},
				{id: uuid.New(), paidAmount: 500000},
			},
			expectError: true,
		},
		{
			name:         "Payment type with only unpaid obligations can be deleted",
			settingValue: "false",
			obligations: []obligationItem{
				{id: uuid.New(), paidAmount: 0},
				{id: uuid.New(), paidAmount: 0},
			},
			expectError: false,
		},
		{
			name:         "Payment type with paid obligations can be deleted in correction mode",
			settingValue: "true",
			obligations: []obligationItem{
				{id: uuid.New(), paidAmount: 250000},
			},
			expectError: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			hasPaid := false
			for _, ob := range tt.obligations {
				if ob.paidAmount > 0 {
					hasPaid = true
					break
				}
			}

			allowed := tt.settingValue == "true"
			var err error
			if hasPaid && !allowed {
				err = domain.ErrExistingPayment
			}

			if tt.expectError && err == nil {
				t.Fatalf("Expected error when deleting payment type with paid obligations, got nil")
			}
			if !tt.expectError && err != nil {
				t.Fatalf("Expected no error, got: %v", err)
			}
		})
	}
}

// TestUpdateSavingTransactionDate tests updating a saving transaction's date
func TestUpdateSavingTransactionDate(t *testing.T) {
	originalDate := time.Date(2026, time.August, 15, 10, 30, 0, 0, time.UTC)
	newDate := time.Date(2026, time.August, 10, 8, 0, 0, 0, time.UTC)

	txn := domain.SavingTransaction{
		ID:        uuid.New(),
		AccountID: uuid.New(),
		Type:      "Deposit",
		Amount:    100000,
		Date:      originalDate,
		Notes:     "Setoran awal",
	}

	// Test map updates with custom date
	updates := map[string]interface{}{
		"amount": 150000.0,
		"notes":  "Setoran dikoreksi",
	}
	dateSlice := []time.Time{newDate}
	if len(dateSlice) > 0 && !dateSlice[0].IsZero() {
		updates["date"] = dateSlice[0]
	}

	if updates["date"] != newDate {
		t.Fatalf("Expected date in updates map to be %v, got %v", newDate, updates["date"])
	}
	if updates["date"] == txn.Date {
		t.Fatalf("Expected updated date to differ from original txn date")
	}

	// Test date parsing logic (as handled in handler)
	dateString := "2026-08-10"
	parsed, err := time.Parse("2006-01-02", dateString)
	if err != nil {
		t.Fatalf("Failed to parse date: %v", err)
	}

	if parsed.Year() != 2026 || parsed.Month() != 8 || parsed.Day() != 10 {
		t.Fatalf("Parsed date values do not match expected: %v", parsed)
	}
}

// TestDeleteBillSafetyPolicy tests the safety check on DeleteBill
func TestDeleteBillSafetyPolicy(t *testing.T) {
	tests := []struct {
		name                  string
		settingValue          string
		settingExists         bool
		hasSuccessPayments    bool
		hasFailedOnlyPayments bool
		expectedDeleteAllowed bool
	}{
		{
			name:                  "Safe mode blocks bill with successful payments",
			settingValue:          "false",
			settingExists:         true,
			hasSuccessPayments:    true,
			expectedDeleteAllowed: false,
		},
		{
			name:                  "Safe mode allows bill with only failed payments",
			settingValue:          "false",
			settingExists:         true,
			hasFailedOnlyPayments: true,
			expectedDeleteAllowed: true,
		},
		{
			name:                  "Safe mode allows completely unpaid bill",
			settingValue:          "false",
			settingExists:         true,
			expectedDeleteAllowed: true,
		},
		{
			name:                  "Correction mode allows bill with successful payments",
			settingValue:          "true",
			settingExists:         true,
			hasSuccessPayments:    true,
			expectedDeleteAllowed: true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			isCorrectionAllowed := tt.settingExists && tt.settingValue == "true"
			var deleteBlocked bool
			if tt.hasSuccessPayments && !isCorrectionAllowed {
				deleteBlocked = true
			}

			if tt.expectedDeleteAllowed && deleteBlocked {
				t.Fatalf("Expected delete to be allowed, but was blocked")
			}
			if !tt.expectedDeleteAllowed && !deleteBlocked {
				t.Fatalf("Expected delete to be blocked, but was allowed")
			}
		})
	}
}

// TestRKASQuantityDecrementationOnObligationDelete verifies the invariant that deleting student obligations
// reduces RKAS quantity by count (down to 0) and keeps PlannedAmount = Quantity * UnitPrice.
func TestRKASQuantityDecrementationOnObligationDelete(t *testing.T) {
	initialQty := 50
	unitPrice := 150000.0
	initialPlanned := float64(initialQty) * unitPrice

	// Delete 1 obligation
	deletedCount := 1
	updatedQty := initialQty - deletedCount
	if updatedQty < 0 {
		updatedQty = 0
	}
	updatedPlanned := float64(updatedQty) * unitPrice

	if updatedQty != 49 {
		t.Fatalf("Expected updated quantity to be 49, got %d", updatedQty)
	}
	if updatedPlanned != 49*150000.0 {
		t.Fatalf("Expected updated planned amount to be %f, got %f", 49*150000.0, updatedPlanned)
	}

	// Delete oversized count (should clamp to 0, not become negative)
	oversizedDelete := 100
	clampedQty := updatedQty - oversizedDelete
	if clampedQty < 0 {
		clampedQty = 0
	}
	clampedPlanned := float64(clampedQty) * unitPrice

	if clampedQty != 0 {
		t.Fatalf("Expected clamped quantity to be 0, got %d", clampedQty)
	}
	if clampedPlanned != 0 {
		t.Fatalf("Expected clamped planned amount to be 0, got %f", clampedPlanned)
	}

	// Initial planned sanity check
	if initialPlanned != 7500000.0 {
		t.Fatalf("Expected initial planned to be 7500000.0, got %f", initialPlanned)
	}
}

