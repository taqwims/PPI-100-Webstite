// TestDeletePaidObligationSafetyPolicy tests the safety check and force delete toggle behavior
func TestDeletePaidObligationSafetyPolicy(t *testing.T) {
	tests := []struct {
		name                 string
		settingValue         string
		settingExists        bool
		paidAmount           float64
		expectedDeleteAllowed bool
		expectedErrMsg       string
	}{
		{
			name:                 "Default safe mode blocks deleting paid obligation",
			settingValue:         "false",
			settingExists:        true,
			paidAmount:           250000,
			expectedDeleteAllowed: false,
			expectedErrMsg:       "tidak bisa menghapus tanggungan yang sudah memiliki riwayat pembayaran",
		},
		{
			name:                 "Missing setting defaults to blocking paid deletion",
			settingValue:         "",
			settingExists:        false,
			paidAmount:           500000,
			expectedDeleteAllowed: false,
			expectedErrMsg:       "tidak bisa menghapus tanggungan yang sudah memiliki riwayat pembayaran",
		},
		{
			name:                 "Unpaid obligation can always be deleted even when setting is false",
			settingValue:         "false",
			settingExists:        true,
			paidAmount:           0,
			expectedDeleteAllowed: true,
			expectedErrMsg:       "",
		},
		{
			name:                 "Correction mode enabled allows deleting paid obligation",
			settingValue:         "true",
			settingExists:        true,
			paidAmount:           350000,
			expectedDeleteAllowed: true,
			expectedErrMsg:       "",
		},
		{
			name:                 "Correction mode enabled allows deleting partially paid obligation",
			settingValue:         "true",
			settingExists:        true,
			paidAmount:           100000,
			expectedDeleteAllowed: true,
			expectedErrMsg:       "",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Simulate the check performed in StudentObligationUsecase.Delete
			isAllowed := tt.settingExists && tt.settingValue == "true"
			var err error
			if tt.paidAmount > 0 && !isAllowed {
				err = domain.ErrExistingPayment
			}

			if tt.expectedDeleteAllowed && err != nil {
				t.Fatalf("Expected deletion to be allowed, but got error: %v", err)
			}

			if !tt.expectedDeleteAllowed && err == nil {
				t.Fatalf("Expected deletion to be blocked for paid obligation, but it was allowed")
			}
		})
	}
}

